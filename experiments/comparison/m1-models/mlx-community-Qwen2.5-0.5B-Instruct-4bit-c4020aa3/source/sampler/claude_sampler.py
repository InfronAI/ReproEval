# reference: https://github.com/lm-sys/FastChat/blob/7899355ebe32117fdae83985cf8ee476d2f4243f/fastchat/conversation.py#L894


class ClaudeCompletionSampler(SamplerBase):

    def __init__(
        self,
        model: str,
        system_message: str | None = None,
        temperature: float = 0.0,  # default in Anthropic example
        max_tokens: int = 4096,
    ):
        self.client = anthropic.Anthropic(timeout=120.0, max_retries=3)
        self.api_key = os.environ.get("ANTHROPIC_API_KEY")  # please set your API_KEY
        self.model = model
        self.system_message = system_message
        self.temperature = temperature
        self.max_tokens = max_tokens
        self.image_format = "base64"

    def _handle_image(
        self,
        image: str,
        encoding: str = "base64",
        format: str = "png",
        fovea: int = 768,
    ):
        new_image = {
            "type": "image",
            "source": {
                "type": encoding,
                "media_type": f"image/{format}",
                "data": image,
            },
        }
        return new_image

    def _handle_text(self, text):
        return {"type": "text", "text": text}

    def _pack_message(self, role, content):
        return {"role": str(role), "content": content}

    def __call__(self, message_list: MessageList) -> SamplerResponse:
        if not common.has_only_user_assistant_messages(message_list):
            raise ValueError("Claude only accepts user and assistant messages")
        kwargs = dict(model=self.model, messages=message_list,
                      max_tokens=self.max_tokens, temperature=self.temperature)
        actual = message_list
        if self.system_message:
            kwargs["system"] = self.system_message
            actual = [{"role": "system", "content": self.system_message}] + message_list
        response = self.client.messages.create(**kwargs)
        text = "".join(block.text for block in response.content if hasattr(block, "text"))
        return SamplerResponse(text, actual, {"usage": response.usage})
